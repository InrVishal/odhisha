/**
 * Renders COPY.md from content/site.ts. Shared by export-copy (writes it)
 * and check-copy (fails if the committed COPY.md is stale).
 */
import { copyValues, fill } from "../content/derived";
import * as c from "../content/site";
import type { Faq, Section, Step } from "../content/site";

const sections = (ss: readonly Section[]) => ss.map((s) => `### ${s.heading}\n\n${s.body.map((p) => fill(p, { ...copyValues, contact: "{contact}" })).join("\n\n")}`).join("\n\n");
const steps = (ss: readonly Step[], ordered = false) => ss.map((s, i) => `${ordered ? `${i + 1}.` : "-"} **${s.title}.** ${fill(s.body)}`).join("\n");
const faqs = (fs: readonly Faq[]) => fs.map((f) => `**${f.q}**\n\n${f.a.join("\n\n")}`).join("\n\n");
const page = (name: string, path: string, description: string) => `## ${name} (\`${path}\`)\n\n_Search description:_ ${description}`;

